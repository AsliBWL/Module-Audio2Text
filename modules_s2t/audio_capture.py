# Импорт библиотек
import queue
import sys
import sounddevice as sd
from typing import Optional, Callable
from modules_s2t.config import Config


class AudioSource:
    """
    Абстрактный класс AudioSource служит базовым интерфейсом для всех источников аудио (микрофон, файл, сетевой поток).
    """
    pass


class MicrophoneSource(AudioSource):
    """
    Класс MicrophoneSource отвечает за захват аудио с микрофона.
    """

    # Конструктор
    def __init__(self, config: Config, callback: Optional[Callable] = None):
        """
        Args:
            config (Config): Объект класса Config со всеми настройками приложения

            callback (Optional[Callable], optional): Функция обратного вызова, которая будет вызвана
                                                     каждый раз при получении нового блока аудио.
                                                     Принимает один аргумент - размер полученных данных (len(indata)).
                                                     Может быть полезна для отладки или отображения уровня сигнала.
        """

        # Сохраняем конфигурацию для доступа к настройкам приложения
        self.config = config

        # Инициализируем потокобезопасную очередь для хранения аудиоданных
        """
        Очередь (работающая по принципу FIFO: первый пришёл — первый ушёл) нужна, потому что звуковая карта (записывает
        аудио) и основная программа (обрабатывает аудио) работают в разных темпах и в разных потоках. Callback звуковой
        карты выполняется в высокоприоритетном потоке, где важна скорость, а распознавание речи - в основном потоке,
        где возможны задержки. Очередь выступает буфером: поток звуковой карты быстро записывает в неё данные,
        а основной поток считывает их, когда готов. Кроме того, Queue автоматически синхронизирует доступ между
        потоками, защищая данные от одновременного изменения.
        """
        self.audio_queue = queue.Queue()

        # Сохраняем пользовательский callback для уведомлений о получении данных
        """
        Пользовательский callback, который вызывается каждый раз, когда в очередь добавляются данные.
        """
        self.callback = callback

        # Создаем внутренний объект аудиопотока от библиотеки sounddevice
        """
        Внутренний объект аудиопотока инициализируется в методе start(), закрывается в методе stop().
        """
        self._stream = None

        # Инициализируем флаг состояния: запущен ли захват аудио
        """
        Используется для проверок и для метода is_running().
        """
        self._is_running = False

    # Внутренняя callback-функция, вызываемая библиотекой sounddevice
    def _audio_callback(self, indata, frames, time_info, status):
        """
        Эта функция выполняется в отдельном потоке (потоке звуковой карты) при поступлении новых данных.
        Её задача - быстро забрать аудиоданные и положить в очередь.

        Args:
            indata (numpy.ndarray): Буфер с аудиоданными. Формат: (frames, channels) с dtype="int16".
            frames (int): Количество семплов в буфере (равно self.config.vad_frame_samples).
            time_info (dict): Информация о времени (не используется в этом коде).
            status (int): Статус записи (не 0, если произошла ошибка или переполнение буфера).
        """

        # Проверяем статус записи: если не 0, значит, произошла проблема (пропуск данных, переполнение и т. д.)
        if status:
            # Выводим сообщение об ошибке в stderr (стандартный поток вывода ошибок), не прерывая работу программы
            # print(f"Audio callback status: {status}", file=sys.stderr)
            pass

        # Конвертируем numpy-массив indata в байты и кладём в потокобезопасную очередь
        """
        Это нужно, потому что объекты bytes занимают меньше памяти и быстрее передаются между потоками.
        bytes(indata) оставляет только данные, без служебной информации.
        Преобразование в bytes() создаёт копию данных, но это необходимо,
        так как indata будет перезаписан при следующем вызове callback.
        """
        self.audio_queue.put(bytes(indata))

        # Если пользователь передал callback, вызываем его с размером полученных данных
        """"
        Это позволяет внешнему коду реагировать на поступление данных (например, обновлять уровень
        сигнала на GUI (графический интерфейс пользователя)).
        """
        if self.callback:
            self.callback(len(indata))

    # Функция запуска захвата аудио с микрофона
    def start(self):
        """
        Открывает аудиопоток и начинает получать данные из callback-функции.
        Если поток уже запущен, метод ничего не делает (игнорирует повторный вызов).

        Raises:
            Exception: Если не удаётся открыть аудиоустройство (например, микрофон не подключён).
        """

        # Защита от повторного запуска: если _stream уже существует, выходим из функции
        if self._stream is not None:
            return

        # Создаём объект RawInputStream для захвата сырого аудио
        """
        RawInputStream возвращает данные в формате int16 без преобразования в float.
        
        Параметры:
        - samplerate - частота дискретизации (sample_rate = 16 кГц из config);
        - blocksize - размер блока данных в семплах (vad_frame_samples = 512 из config);
        - device - аудиоустройство, с которым библиотека sounddevice должна работать
          (например, микрофон ноутбука, внешняя USB-гарнитура, виртуальный аудиокабель),
          если device=None, то по умолчанию используется системное устройство ввода,
          инструкция о том, как найти нужное аудиоустройство, представлена в файле
          audio_device_selection.txt;
        - dtype - числовой формат, в котором библиотека sounddevice будет передавать
          вам аудиоданные из callback-функции ("int16", т. е. 16-битные целые числа -
          это стандарт для аудио;
        - channels - количество каналов аудио, channels=1 - это моно, channels=2 -
          это стерео (1 канал, т. к. для условий промышленного предприятия нет
          необходимости в распознавания аудио в формате стерео);
        - callback - функция, вызываемая при поступлении новых данных
        """
        self._stream = sd.RawInputStream(
            samplerate=self.config.sample_rate,
            blocksize=self.config.vad_frame_samples,
            device=None,
            dtype="int16",
            channels=1,
            callback=self._audio_callback
        )

        # Запускаем аудиопоток, т. е. открываем контекстный менеджер потока
        self._stream.__enter__()

        # Устанавливаем флаг, что захват запущен
        self._is_running = True

    # Функция остановки захвата аудио с микрофона
    def stop(self):
        """
        Закрывает аудиопоток и освобождает связанные ресурсы.
        После остановки объект MicrophoneSource можно переиспользовать, вызвав start() снова.
        """

        # Проверяем, существует ли поток
        if self._stream:
            # Останавливаем аудиопоток, т. е. закрываем контекстный менеджер потока
            """
            Аргументы None, None, None означают, что при работе потока не было ошибок.
            Если бы была ошибка, сюда были бы переданы информация о типе ошибки,
            объект ошибки и traceback для её обработки.
            """
            self._stream.__exit__(None, None, None)
            # Обнуляем ссылку на поток, чтобы можно было перезапустить
            self._stream = None

        # Сбрасываем флаг состояния
        self._is_running = False

        """
        Примечание: очередь audio_queue НЕ очищается!
        Это сделано намеренно, чтобы данные, которые уже попали в очередь,
        могли быть обработаны после остановки.
        Если нужно полностью очистить всё, это должна делать вызывающая сторона.
        """

    # Функция, возвращающая следующий фрейм из очереди
    def get_audio_chunk(self):
        """
        Это неблокирующий метод: он проверяет очередь и мгновенно возвращает результат,
        не дожидаясь появления данных.
        Метод использует get_nowait() вместо get(), чтобы не блокировать основной поток программы.
        Это позволяет основному циклу выполнять другие задачи (например, VAD-анализ) даже если
        данных ещё нет.

        Returns:
            Optional[bytes]: Байтовый буфер с аудиоданными (int16) размером
                             vad_frame_samples * bytes_per_sample байт,
                             или None, если очередь пуста.
        """

        # Пытаемся
        try:
            # получить элемент из очереди без ожидания (non-blocking)
            return self.audio_queue.get_nowait()
        # Если очередь пустая, то выбрасывается исключение queue.Empty
        except queue.Empty:
            # возвращаем None
            return None

    # Функция, проверяющая, запущен ли захват аудио
    def is_running(self):
        """
        Returns:
            bool: True, если поток открыт и данные поступают, False в противном случае.
        """

        # Возвращаем флаг состояния
        return self._is_running
