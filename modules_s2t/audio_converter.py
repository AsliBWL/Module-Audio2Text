# Импорт библиотек
import numpy as np


class AudioConverter:
    """
    Утилитарный класс AudioConverter отвечает за конвертацию аудио.
    """

    # Функция конвертации PCM int16 в float32 в диапазоне -1..1
    @staticmethod  # Метод класса будет статическим
    def pcm16_to_float32(audio_bytes: bytes):
        """
        PCM (Pulse Code Modulation) - это способ цифрового представления
        аналогового звукового сигнала. Каждый замер амплитуды называется "семпл".

        Причина конвертации из PCM int16 в float32 в диапазоне -1..1 -
        нейросети работают с float32, потому что:
        - градиенты и обновления весов требуют дробных чисел;
        - операции с float32 быстрее на GPU, чем с int16;
        - нормализация в диапазон -1..1 стабилизирует обучение.

        Args:
            audio_bytes (bytes): Входные байты с аудиоданными.

        Returns:
            np.ndarray: Массив float32 с нормализованными значениями в диапазоне -1..1.
                        Длина массива равна количеству семплов.

        Пример:
            Вход:  bytes(b'\x2a\x00\x49\x00')
            Интерпретируем как int16:
            - Первые 2 байта \x2a\x00 = 0x002A = 42
            - Следующие 2 байта \x49\x00 = 0x0049 = 73
            Промежуточный массив int16: [42, 73]
            После .astype(np.float32): [42.0, 73.0]
            После деления на 32768: [42/32768, 73/32768] = [0.00128, 0.00223]
        """

        # Преобразуем байты в массив int16
        """
        np.frombuffer(audio_bytes, dtype=np.int16) читает байты как последовательность 16-битных целых чисел.
        Байты интерпретируются в порядке little-endian (младший байт сначала).
        Это стандартный порядок байт для WAV-файлов и большинства аудиодрайверов Windows/Linux.
        """
        int16_array = np.frombuffer(audio_bytes, dtype=np.int16)

        # Преобразуем массив int16 в массив float32
        float32_array = int16_array.astype(np.float32)

        # Нормализуем массив float32 в диапазон -1..1
        normalized_array = float32_array / 32768.0

        # Возвращаем массив float32 с нормализованными значениями в диапазоне -1..1
        return normalized_array

    # Функция объединения нескольких байтовых фрагментов в один float32 массив
    @staticmethod  # Метод класса будет статическим
    def bytes_to_float32_samples(audio_bytes_list: list):
        """
        Причина объединения нескольких байтовых фрагментов в один:
        в реальном времени аудиоданные приходят маленькими порциями (фрагментами),
        но для распознавания речи накопленный за время фразы аудио нужно передать модели
        как один непрерывный массив.

        Например, во время разговора накопились фрагменты:
        - Фрагмент 1: 512 семплов (за 32 мс)
        - Фрагмент 2: 512 семплов (ещё за 32 мс)
        - Фрагмент 3: 256 семплов (последние 16 мс перед паузой)
        Эта функция склеит их в один массив: 512 + 512 + 256 = 1280 семплов.

        Args:
            audio_bytes_list (list): Список байтовых объектов.
            Каждый элемент — это bytes с аудиоданными в формате int16.

        Returns:
            np.ndarray: Объединённый массив float32 с нормализованными значениями.
        """

        # Для каждого байтового фрагмента из входного списка делаем преобразование в float32
        float_arrays = [AudioConverter.pcm16_to_float32(b) for b in audio_bytes_list]

        # Склеиваем все массивы в один
        result = np.concatenate(float_arrays)

        # Возвращаем объединенный float32 массив
        return result
