# Импорт библиотек
from abc import ABC, abstractmethod
import numpy as np
from silero_vad import load_silero_vad, VADIterator
from config import Config


class VADInterface(ABC):
    """
    Абстрактный класс VADInterface отвечает за детекцию голосовой активности.

    ABC (Abstract Base Class) — абстрактный базовый класс.
    Это означает, что от этого класса нельзя создать объект.

    Его задача - задать "контракт", который обязаны выполнять все классы-наследники:
    - Любой детектор VAD должен уметь обрабатывать фрейм (process_frame)
    - Любой детектор VAD должен уметь сбрасывать состояние (reset)
    """

    # Функция обработки одного фрейма (отрезка аудио)
    """
    Метод класса будет абстрактным, т. е. не имеет тела,
    но обязан быть реализован в классе наследнике
    """
    @abstractmethod
    def process_frame(self, frame_float: np.ndarray):
        """
        Args:
            frame_float (np.ndarray): Фрейм аудио в формате float32.

        Returns:
            dict: Словарь с информацией о событии, или None если ничего не произошло.
                  Возможные значения:
                  - {'start': timestamp} - началась речь (timestamp — время в секундах);
                  - {'end': timestamp} - речь закончилась (timestamp — время в секундах);
                  - None - нет изменений (продолжается речь или продолжается тишина).
        """

        pass

    # Функция сброса внутреннего состояния детектора голосовой активности
    """
    Метод класса будет абстрактным, т. е. не имеет тела,
    но обязан быть реализован в классе наследнике
    """
    @abstractmethod
    def reset(self):
        """
        Причина сброса внутреннего состояния детектора голосовой активности:
        После того как речь закончилась и мы получили {'end'}, детектор может сохранить
        внутренние буферы (последние фреймы, статистику). Если начать новую сессию распознавания,
        эти старые данные могут помешать. reset() очищает всё внутреннее состояние,
        подготавливая детектор к обработке нового аудиопотока.
        """

        pass


class SileroVADDetector(VADInterface):
    """
    Реализация VAD с использованием модели Silero.
    """

    # Конструктор
    def __init__(self, config: Config):
        """
        Args:
            config (Config): Объект класса Config со всеми настройками приложения
        """

        # Сохраняем конфигурацию для доступа к настройкам приложения
        self.config = config

        # Загружаем модель Silero VAD в формате ONNX
        """
        ONNX (Open Neural Network Exchange) - формат моделей машинного обучения.
        Преимущества ONNX:
        - Быстрее, чем PyTorch (оптимизированный рантайм)
        - Не требует установки PyTorch (меньше зависимостей)
        - Кроссплатформенность (работает на CPU/GPU)
        """
        self._vad_model = load_silero_vad(onnx=True)

        # Создаём итератор VAD, который поддерживает состояние между вызовами
        """
        VADIterator запоминает:
        - был ли предыдущий фрейм речью или тишиной;
        - как долго длится текущий речевой сегмент;
        - сколько времени длится тишина (для определения конца фразы).
        """
        self._vad_iterator = VADIterator(
            self._vad_model,
            threshold=config.vad_threshold,                          # порог срабатывания модели VAD
            sampling_rate=config.sample_rate,                        # частота дискретизации аудио
            min_silence_duration_ms=config.min_silence_duration_ms,  # пауза для конца фразы
            speech_pad_ms=config.speech_pad_ms,                      # паддинг (тишина) вокруг речи
        )

    # Функция обработки одного фрейма (отрезка аудио)
    def process_frame(self, frame_float: np.ndarray):
        """
        Args:
            frame_float (np.ndarray): Фрейм аудио в формате float32.

        Returns:
            dict: Словарь с информацией о событии, или None если ничего не произошло.
                  Возможные значения:
                  - {'start': timestamp} - началась речь (timestamp — время в секундах);
                  - {'end': timestamp} - речь закончилась (timestamp — время в секундах);
                  - None - нет изменений (продолжается речь или продолжается тишина).
        """

        # Возвращаем словарь с временем начала и конца речевого сегмента или None
        return self._vad_iterator(frame_float)

    # Функция сброса внутреннего состояния детектора голосовой активности
    def reset(self):

        # Сбрасывает внутреннее состояние VAD итератора
        self._vad_iterator.reset_states()
